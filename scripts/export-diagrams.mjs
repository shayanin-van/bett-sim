// Renders one showcase example per diagram tool from @skooldio/skooldio-lams-markdown
// into diagrams/, and writes diagrams/index.js — the manifest the Diagrams tab reads.
//
//   1. in skooldio-lams-markdown: pnpm build && pnpm preview:dev   (serves port 5199)
//   2. here: node scripts/export-diagrams.mjs [--tool <key>] [--limit N] [--port 5199]
//      --no-render rewrites the manifest only, reusing the PNGs already on disk.
//
// The manifest is a plain script assigning window.DIAGRAM_INDEX rather than JSON fetched at
// runtime, so the page also works opened straight off disk (file:// blocks fetch).
//
// The live editor in the diagram panel needs vendor/lams-diagram.js — a standalone bundle of
// the package's tool registry, which is not published to a public registry. Rebuild it with:
//
//   node scripts/build-vendor-bundle.mjs
//
// LAMS_MARKDOWN overrides where the package lives (default: sibling checkout).
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PKG = resolve(
  process.env.LAMS_MARKDOWN ?? join(__dirname, "..", "..", "skooldio-lams-markdown"),
);
const OUT = join(__dirname, "..", "diagrams");

const argv = process.argv.slice(2);
const arg = (n) => (argv.indexOf(`--${n}`) >= 0 ? argv[argv.indexOf(`--${n}`) + 1] : null);
const limit = arg("limit") ? Number(arg("limit")) : Infinity;
const only = arg("tool");
const noRender = argv.includes("--no-render");

// The package is ESM-only and unpublished outside the private registry, so load it and the
// shared headless renderer straight out of the checkout.
const { TOOL_REGISTRY, TOOL_SHOWCASE, TOOL_GROUPS } = await import(
  new URL(`file:///${PKG}/dist/index.js`)
);

const groupLabel = Object.fromEntries(TOOL_GROUPS.map((g) => [g.key, g.label]));
const jobs = Object.entries(TOOL_REGISTRY)
  .filter(([key]) => !only || key === only)
  .flatMap(([key, tool]) => {
    const ex = TOOL_SHOWCASE[key]?.examples?.[0];
    if (!ex) return [];
    return [
      {
        key,
        file: `${key}.png`,
        displayName: tool.meta.displayName,
        group: tool.meta.group,
        groupLabel: groupLabel[tool.meta.group] ?? "Other",
        title: ex.title,
        description: ex.description,
        // what the live editor feeds back to TOOL_REGISTRY[key].render()
        name: tool.declaration.name,
        params: ex.params,
      },
    ];
  })
  .slice(0, limit);

mkdirSync(OUT, { recursive: true });

let done = jobs;
if (!noRender) {
  const { createRenderer } = await import(new URL(`file:///${PKG}/eval/lib/render.mjs`));
  const renderer = await createRenderer({ port: arg("port") ?? 5199, concurrency: 4 });
  done = [];
  let next = 0;
  await Promise.all(
    Array.from({ length: 4 }, async () => {
      while (next < jobs.length) {
        const job = jobs[next++];
        const r = await renderer.render(
          JSON.stringify({ name: job.name, parameters: job.params }),
          join(OUT, job.file),
        );
        if (!r.ok || r.isError) {
          console.log(`FAIL ${job.key}: ${r.errorText.slice(0, 120)}`);
          continue;
        }
        done.push(job);
        console.log(`ok   ${job.key}`);
      }
    }),
  );
  await renderer.close();
}

const order = TOOL_GROUPS.map((g) => g.key);
done.sort(
  (a, b) =>
    order.indexOf(a.group) - order.indexOf(b.group) ||
    a.displayName.localeCompare(b.displayName),
);
writeFileSync(
  join(OUT, "index.js"),
  `// Generated by scripts/export-diagrams.mjs — do not edit.\nwindow.DIAGRAM_INDEX = ${JSON.stringify(done, null, 2)};\n`,
);
console.log(`\n${done.length}/${jobs.length} diagrams -> ${OUT}`);
