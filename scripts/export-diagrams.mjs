// Renders one showcase example per diagram tool from @skooldio/skooldio-lams-markdown into
// diagrams/, and writes the two files the Diagrams tab reads:
//
//   diagrams/index.js    window.DIAGRAM_INDEX — one entry per tool
//   vendor/en-labels.js  window.toEnglish(root) — the Thai -> English swap, shared with the
//                        live gallery so an edited diagram reads the same as its thumbnail
//
//   node scripts/export-diagrams.mjs [--tool <key>] [--limit N]
//   node scripts/export-diagrams.mjs --no-render     manifest and label script only
//
// Rendering needs vendor/lams-diagram.js (node scripts/build-vendor-bundle.mjs) and a Chrome or
// Edge install; it serves scripts/render-page.html itself, so no dev server is required.
//
// LAMS_MARKDOWN overrides where the package lives (default: sibling checkout).
import { createServer } from "node:http";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const PKG = resolve(
  process.env.LAMS_MARKDOWN ?? join(ROOT, "..", "skooldio-lams-markdown"),
);
const OUT = join(ROOT, "diagrams");

const argv = process.argv.slice(2);
const arg = (n) => (argv.indexOf(`--${n}`) >= 0 ? argv[argv.indexOf(`--${n}`) + 1] : null);
const limit = arg("limit") ? Number(arg("limit")) : Infinity;
const only = arg("tool");
const noRender = argv.includes("--no-render");

// The package is ESM-only and unpublished outside the private registry, so load it straight
// out of the checkout.
const { TOOL_REGISTRY, TOOL_SHOWCASE, TOOL_GROUPS } = await import(
  new URL(`file:///${PKG}/dist/index.js`)
);

// ── English labels ───────────────────────────────────────────────────────────────────────
// The examples are written for Thai classrooms and some renderers hard-code Thai captions
// (electrode roles, axis names, the gel's migration arrow). Example data is translated here,
// where it also reaches the JSON editor; the rest is swapped in the DOM after rendering, by
// the script below, which both the export and the live gallery run.
const EN = Object.entries(JSON.parse(readFileSync(join(__dirname, "en-labels.json"), "utf8")))
  .filter(([thai]) => !thai.startsWith("_"))
  .sort((a, b) => b[0].length - a[0].length); // longest first: "Metaphase I" before "Meiosis I"
const THAI = /[฀-๿]/;
const untranslated = new Map();

function toEnglish(value, key) {
  if (typeof value === "string") {
    if (!THAI.test(value)) return value;
    let out = value;
    for (const [thai, english] of EN) out = out.split(thai).join(english);
    if (THAI.test(out)) untranslated.set(value, key);
    return out;
  }
  if (Array.isArray(value)) return value.map((v) => toEnglish(v, key));
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, toEnglish(v, key)]));
  }
  return value;
}

mkdirSync(join(ROOT, "vendor"), { recursive: true });
writeFileSync(
  join(ROOT, "vendor", "en-labels.js"),
  `// Generated by scripts/export-diagrams.mjs from scripts/en-labels.json — do not edit.
window.EN_LABELS = ${JSON.stringify(EN)};
window.toEnglish = function (root) {
  var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  var node;
  while ((node = walker.nextNode())) {
    var text = node.nodeValue;
    if (!/[\\u0E00-\\u0E7F]/.test(text)) continue;
    for (var i = 0; i < window.EN_LABELS.length; i++) {
      text = text.split(window.EN_LABELS[i][0]).join(window.EN_LABELS[i][1]);
    }
    node.nodeValue = text;
  }
};
`,
);

// ── the gallery entries ──────────────────────────────────────────────────────────────────
const groupLabel = Object.fromEntries(TOOL_GROUPS.map((g) => [g.key, g.label]));

// The tool description is written for the model that drives the tool: a paragraph on what the
// diagram is, then paragraphs of usage rules. The first paragraph is the part a visitor wants.
function summarise(description) {
  const first = description
    .split(/\n\s*\n/)[0]
    // the descriptions gloss each English term with its Thai curriculum name — "galvanic cell
    // (เซลล์กัลวานิก)" — which an English reader does not need
    .replace(/\s*\([^()]*[฀-๿][^()]*\)/g, "")
    .replace(/ม\.\d/g, "upper-secondary") // \b does not apply to Thai script
    .replace(/\s+/g, " ")
    .trim();
  if (first.length <= 260) return first;
  const cut = first.slice(0, 260);
  const stop = Math.max(cut.lastIndexOf(". "), cut.lastIndexOf("; "));
  return (stop > 120 ? cut.slice(0, stop) : cut.replace(/\s\S*$/, "")) + "…";
}

const jobs = Object.entries(TOOL_REGISTRY)
  .filter(([key]) => !only || key === only)
  .flatMap(([key, tool]) => {
    const ex = TOOL_SHOWCASE[key]?.examples?.[0];
    if (!ex) return [];
    return [
      {
        key,
        file: `${key}.png`,
        displayName: tool.meta.displayName,
        group: tool.meta.group,
        groupLabel: groupLabel[tool.meta.group] ?? "Other",
        title: toEnglish(ex.title, key),
        summary: toEnglish(summarise(tool.declaration.description), key),
        // what the live editor feeds back to TOOL_REGISTRY[key].render()
        name: tool.declaration.name,
        params: toEnglish(ex.params, key),
      },
    ];
  })
  .slice(0, limit);

if (untranslated.size) {
  console.error(`\n${untranslated.size} Thai string(s) missing from scripts/en-labels.json:\n`);
  for (const [text, key] of untranslated) console.error(`  ${key}: ${JSON.stringify(text)}`);
  process.exit(1);
}

// ── render ───────────────────────────────────────────────────────────────────────────────
mkdirSync(OUT, { recursive: true });

let done = jobs;
if (!noRender) {
  // scripts/render-page.html and the two vendor scripts, on a port the harness can drive.
  const files = {
    "/": [join(__dirname, "render-page.html"), "text/html"],
    "/lams-diagram.js": [join(ROOT, "vendor", "lams-diagram.js"), "text/javascript"],
    "/en-labels.js": [join(ROOT, "vendor", "en-labels.js"), "text/javascript"],
  };
  const server = createServer((req, res) => {
    const entry = files[req.url.split("?")[0]];
    if (!entry) return res.writeHead(404).end();
    res.writeHead(200, { "content-type": entry[1] }).end(readFileSync(entry[0]));
  });
  await new Promise((r) => server.listen(0, "127.0.0.1", r));
  const port = server.address().port;

  const { createRenderer } = await import(new URL(`file:///${PKG}/eval/lib/render.mjs`));
  const renderer = await createRenderer({ port, concurrency: 4 });
  done = [];
  let next = 0;
  await Promise.all(
    Array.from({ length: 4 }, async () => {
      while (next < jobs.length) {
        const job = jobs[next++];
        const r = await renderer.render(
          JSON.stringify({ key: job.key, name: job.name, parameters: job.params }),
          join(OUT, job.file),
        );
        if (!r.ok || r.isError) {
          console.log(`FAIL ${job.key}: ${r.errorText.slice(0, 160)}`);
          continue;
        }
        done.push(job);
        console.log(`ok   ${job.key}`);
      }
    }),
  );
  await renderer.close();
  server.close();
}

// A partial run re-renders a thumbnail or two; writing the manifest from it would drop every
// other tool out of the gallery.
if (only || limit !== Infinity) {
  console.log(`\n${done.length}/${jobs.length} diagrams -> ${OUT} (manifest left alone)`);
  process.exit(0);
}

const order = TOOL_GROUPS.map((g) => g.key);
done.sort(
  (a, b) =>
    order.indexOf(a.group) - order.indexOf(b.group) ||
    a.displayName.localeCompare(b.displayName),
);
writeFileSync(
  join(OUT, "index.js"),
  `// Generated by scripts/export-diagrams.mjs — do not edit.\nwindow.DIAGRAM_INDEX = ${JSON.stringify(done, null, 2)};\n`,
);
console.log(`\n${done.length}/${jobs.length} diagrams -> ${OUT}`);
